local W = require("wow")
test("old showFilters seed the defaults", function()
    local GL = W.load({ db = { settings = { showFilters = { level = false } } } })
    eq(GL.settings.logHidden.level, true, "level hidden")
    eq(GL.settings.showFilters, nil, "old setting gone")
end)
test("fresh install hides Leveled", function()
    local GL = W.load()
    local n = 0
    for _ in pairs(GL.settings.logHidden) do n = n + 1 end
    eq(n, 1, "one hidden kind")
    eq(GL.settings.logHidden.level, true, "level")
end)
test("a visit's change does not stick", function()
    local GL = W.load()
    GL:ResetLogFilter()
    GL:SetLogKindShown("level", true)
    eq(GL:LogKindShown("level"), true, "shown during the visit")
    GL:ResetLogFilter()
    eq(GL:LogKindShown("level"), false, "hidden again")
end)
test("goLog filter shows only its kinds", function()
    local GL = W.load()
    GL:SetLogFilterOnly({ join = true })
    eq(GL:LogKindShown("join"), true, "join")
    eq(GL:LogKindShown("leave"), false, "leave")
end)
