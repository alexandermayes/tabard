local W = require("wow")
local function fresh()
    local GL = W.load()
    W.setRoster({ { name = "Ooh Woo", rank = "Member", rankIndex = 3, level = 20, class = "MAGE" } })
    W.scan(GL)
    return GL, GL:Guild()
end
test("an old event lands before newer ones", function()
    local GL, g = fresh()
    local now = GL:Now()
    GL:AddEvent(g, "level", { who = "Ooh Woo", level = 21, from = 20 }, now)
    GL:AddEvent(g, "join", { who = "Ooh Woo", src = "game" }, now - 5 * 86400)
    eq(g.events[1].k, "join", "oldest first") eq(g.events[#g.events].k, "level", "newest last")
end)
test("FindEvent finds a recent join after an old event was appended", function()
    local GL, g = fresh()
    local now = GL:Now()
    GL:AddEvent(g, "join", { who = "Ooh Woo" }, now - 1800)
    GL:AddEvent(g, "leave", { who = "Old Timer", src = "game" }, now - 6 * 86400)
    ok(GL:FindEvent(g, "join", "Ooh Woo", now, 3 * 3600) ~= nil, "found")
end)
test("AwaySummary counts everything after the marker", function()
    local GL, g = fresh()
    local now = GL:Now()
    GL:AddEvent(g, "join", { who = "Ooh Woo" }, now - 600)
    GL:AddEvent(g, "leave", { who = "Old Timer", src = "game" }, now - 6 * 86400)
    eq(GL:AwaySummary(g, now - 3600).joins, 1, "one join since")
end)
test("SortEvents sorts and keeps ties in order", function()
    local GL, g = fresh()
    g.events = { { t = 30, k = "a" }, { t = 10, k = "b" }, { t = 30, k = "c" }, { t = 20, k = "d" } }
    GL:SortEvents(g)
    eq(g.events[1].k .. g.events[2].k .. g.events[3].k .. g.events[4].k, "bdac", "order")
end)
