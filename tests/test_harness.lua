local W = require("wow")
test("addon loads and makes a ledger", function()
    local GL = W.load()
    W.setRoster({ { name = "Ooh Woo", rank = "Member", rankIndex = 3, level = 20, class = "MAGE" } })
    W.scan(GL)
    local guild = GL:Guild()
    eq(guild.name, "Test Guild", "guild name")
    ok(guild.members["Ooh Woo"] ~= nil, "member seeded")
end)
test("fake clock drives GL:Now", function()
    local GL = W.load()
    local t = GL:Now()
    W.advance(3600)
    eq(GL:Now() - t, 3600, "advanced an hour")
end)
test("player name joins first name and surname", function()
    local GL = W.load()
    eq(GL:PlayerName(), "Zev Zev", "player name")
end)
test("game log entries come back with their age", function()
    local GL = W.load()
    W.setGameLog({ { kind = "join", p1 = "New Guy", hoursAgo = 30 } })
    local kind, p1, _, _, y, m, d, h = GetGuildEventInfo(1)
    eq(kind, "join", "kind") eq(p1, "New Guy", "name") eq(d * 24 + h, 30, "hours ago")
end)
test("W.events filters by kind and name", function()
    local GL = W.load()
    W.setRoster({ { name = "Ooh Woo", rank = "Member", rankIndex = 3, level = 20, class = "MAGE" } })
    W.scan(GL)
    local guild = GL:Guild()
    GL:AddEvent(guild, "join", { who = "X" })
    eq(#W.events(guild, "join", "X"), 1, "kind and name")
    eq(#W.events(guild, "leave", "X"), 0, "other kind")
    eq(#W.events(guild, nil, "X"), 1, "any kind")
end)
